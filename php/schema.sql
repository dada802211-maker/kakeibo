-- 単一利用者の認証情報。平文パスワードは保存しません。
CREATE TABLE IF NOT EXISTS kb_account (
 id TINYINT UNSIGNED PRIMARY KEY,
 password_hash VARCHAR(255) NOT NULL,
 auth_version INT UNSIGNED NOT NULL DEFAULT 1,
 failed_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 locked_until DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- id が画面で入力する管理番号です。実際のクレジットカード番号は保存しません。
CREATE TABLE IF NOT EXISTS kb_cards (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 closing_day TINYINT UNSIGNED NOT NULL DEFAULT 31
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kb_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kb_expenses (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 purchased_on DATE NOT NULL,
 card_id INT UNSIGNED NOT NULL,
 item_id INT UNSIGNED NOT NULL,
 amount INT UNSIGNED NOT NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_purchase (purchased_on, card_id),
 FOREIGN KEY (card_id) REFERENCES kb_cards(id),
 FOREIGN KEY (item_id) REFERENCES kb_items(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
